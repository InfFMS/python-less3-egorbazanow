# с клавиатуры вводятся числа, ввод завершается числом 0.
# Определить, сколько было введено простых натуральных чисел
# (которые делятся только сами на себя и на 1), и сколько составных.

n = 0
p = 0
x = 0
for i in range(1, 100000):
    x = 0
    y = int(input())
    if y == 0:
        break
    else:
        for j in range(2, y):
            if y % i == 0:
                x += 1
        if x == 0:
            p +=1
        else:
            n +=1
print(p, n)