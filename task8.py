# с клавиатуры вводится число N, а затем – N целых чисел.
# Определить, сколько было введено положительных и
# сколько отрицательных чисел (нули не считать!).
p = 0
neg=0
n = int(input())
N = int(input())
for i in range(0, N):
    n = int(input())
    if n < 0:
        neg+=1
    elif n>0:
        p+=1
